-- Missions planned on the map and their assignment to drones.
--   mission.waypoints: [{"lat": .., "lon": .., "alt": ..}, ...], alt in metres above home (30..500),
--   at least 2 points; loop = true flies them again and again (DO_JUMP back to the first).
--   drone_mission: the mission last assigned to (uploaded to) each drone; last_seq is the
--   mission item the drone last reported as current (MISSION_CURRENT.seq, 1 = first waypoint)
--   while flying it, so RESUME_MISSION can upload it again from there.
CREATE TABLE mission (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text        NOT NULL,
    waypoints  jsonb       NOT NULL,
    loop       boolean     NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_mission_waypoints CHECK (jsonb_typeof(waypoints) = 'array' AND jsonb_array_length(waypoints) >= 2)
);

CREATE TABLE drone_mission (
    drone_id    integer     PRIMARY KEY,
    -- Deleting a mission also ends its assignments.
    mission_id  bigint      NOT NULL REFERENCES mission (id) ON DELETE CASCADE,
    assigned_at timestamptz NOT NULL,
    last_seq    integer
);

CREATE INDEX idx_drone_mission_mission_id ON drone_mission (mission_id);
